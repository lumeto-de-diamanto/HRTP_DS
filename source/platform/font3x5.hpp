// Returns one glyph row as a 3-bit mask in bits 3..1.
static inline uint8_t font3x5_line(char data, int line)
{
    const unsigned char *g = font4x6[(unsigned char)data - 32];
    int ln = line - ((g[1] & 1) ? 1 : 0);
    uint8_t pixel = 0;
    if (ln == 0)
        pixel = g[0] >> 4;
    else if (ln == 1)
        pixel = g[0] >> 1;
    else if (ln == 2)
        pixel = ((g[0] & 0x03) << 2) | (g[1] & 0x02);
    else if (ln == 3)
        pixel = g[1] >> 4;
    else if (ln == 4)
        pixel = g[1] >> 1;
    return pixel & 0x0E;
}
