int Sin8(unsigned char angle)
{
    return (angle < 64) ? SinTable8[angle] : CosTable8[angle - 64];
}

int Cos8(unsigned char angle)
{
    return CosTable8[angle];
}

// iatan2.asm: table-based atan2 returning a 256-step angle.
int iatan2(int y, int x)
{
    if ((x | y) == 0)
        return 0;

    int ay = (y < 0) ? -y : y;
    int ax = (x < 0) ? -x : x;
    int a;

    if (ax == ay) {
        a = 32;
    } else if (ax > ay) {
        a = AtanTable8[(ay << 8) / ax];
    } else {
        a = 64 - AtanTable8[(ax << 8) / ay];
    }
    if (x < 0)
        a = -a + 128;
    if (y < 0)
        a = -a;
    return a & 0xFF;
}
