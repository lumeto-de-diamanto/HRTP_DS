#!/usr/bin/env python3
"""Build the compact 16x16 PC-98 JIS font used by the DS port.

The Anex86/Neko Project II 2048x2048 font sheet is a 128x128 grid of
16x16 slots. For a two-byte JIS code 0xKKTT, the glyph is at:

    slot column = KK - 0x20   (ku)
    slot row    = TT          (ten + 0x20)

This is the PC-98 CG-ROM layout.  We scan the original game's production
Shift-JIS string headers so the output contains only glyphs the game uses.
debug.hpp is deliberately excluded. All fullwidth A-Z/a-z are added because
name entry selects them as ranges rather than spelling each one in a string.
"""

import argparse
import re
import struct
import sys
from pathlib import Path

SHEET_SIZE = 2048
SLOT_SIZE = 16


def strip_c_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//.*", "", text)


def required_chars(source_dir: Path) -> set[str]:
    chars: set[str] = set()
    quote_re = re.compile(r'''(["'])(.*?)(?<!\\)\1''')

    for path in sorted(source_dir.glob("*.hpp")):
        if path.name == "debug.hpp":
            continue
        text = strip_c_comments(path.read_bytes().decode("cp932"))
        for match in quote_re.finditer(text):
            chars.update(c for c in match.group(2) if ord(c) > 0x7F)

    # REGIST's name-entry code walks these ranges dynamically.
    chars.update(chr(ord("Ａ") + i) for i in range(26))
    chars.update(chr(ord("ａ") + i) for i in range(26))
    chars.update("０１２３４５６７８９")
    return chars


def sjis_to_jis(pair: bytes) -> int:
    if len(pair) != 2:
        raise ValueError(f"expected a two-byte Shift-JIS character: {pair!r}")
    lead, trail = pair
    if not ((0x81 <= lead <= 0x9F) or (0xE0 <= lead <= 0xEF)):
        raise ValueError(f"unsupported Shift-JIS lead byte 0x{lead:02X}")

    row = ((lead - (0x81 if lead < 0xA0 else 0xC1)) * 2) + 0x21
    if trail >= 0x9F:
        row += 1
        cell = trail - 0x7E
    else:
        if trail > 0x7E:
            trail -= 1
        cell = trail - 0x1F
    return (row << 8) | cell


def load_bitmap(path: Path) -> tuple[bytes, int]:
    data = path.read_bytes()
    if data[:2] != b"BM":
        raise ValueError("font sheet is not a BMP")
    width, height = struct.unpack_from("<ii", data, 18)
    bpp = struct.unpack_from("<H", data, 28)[0]
    if width != SHEET_SIZE or abs(height) != SHEET_SIZE or bpp != 1:
        raise ValueError("font sheet must be a 2048x2048 1bpp BMP")
    return data, struct.unpack_from("<I", data, 10)[0]


def glyph_rows(data: bytes, pixel_offset: int, jis: int) -> list[int]:
    ku = (jis >> 8) & 0xFF
    ten = jis & 0xFF
    x0 = (ku - 0x20) * SLOT_SIZE
    y0 = ten * SLOT_SIZE
    row_bytes = SHEET_SIZE // 8
    rows: list[int] = []

    for gy in range(SLOT_SIZE):
        bmp_y = SHEET_SIZE - 1 - (y0 + gy)
        bits = 0
        for gx in range(SLOT_SIZE):
            x = x0 + gx
            source = data[pixel_offset + bmp_y * row_bytes + x // 8]
            ink = 1 - ((source >> (7 - (x & 7))) & 1)
            bits = (bits << 1) | ink
        rows.append(bits)
    return rows


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("sheet", type=Path)
    parser.add_argument("source_dir", type=Path)
    parser.add_argument("outdir", type=Path)
    parser.add_argument("--name", default="font16x16")
    args = parser.parse_args()

    try:
        by_jis: dict[int, str] = {}
        for char in required_chars(args.source_dir):
            encoded = char.encode("cp932")
            jis = sjis_to_jis(encoded)
            by_jis.setdefault(jis, char)
        data, pixel_offset = load_bitmap(args.sheet)
    except (OSError, UnicodeError, ValueError, struct.error) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    entries = sorted(by_jis.items())
    lines = [
        f"// Generated by tools/font16x16.py from {args.sheet.name} -- do not edit.",
        "// Compact PC-98 16x16 JIS set used by TH01 production strings.",
        "#pragma once",
        "",
        f"#define FONT16X16_GLYPH_COUNT {len(entries)}",
        "",
        f"static const unsigned short {args.name}_jis[FONT16X16_GLYPH_COUNT] = {{",
    ]
    for jis, char in entries:
        lines.append(f"    0x{jis:04X}, // {char}")
    lines.extend([
        "};",
        "",
        f"static const unsigned short {args.name}_rows[FONT16X16_GLYPH_COUNT][16] = {{",
    ])
    for jis, char in entries:
        body = ", ".join(f"0x{row:04X}" for row in glyph_rows(data, pixel_offset, jis))
        lines.append(f"    {{{body}}}, // {char} JIS 0x{jis:04X}")
    lines.extend(["};", ""])

    args.outdir.mkdir(parents=True, exist_ok=True)
    out = args.outdir / f"{args.name}.h"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out} ({len(entries)} glyphs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
