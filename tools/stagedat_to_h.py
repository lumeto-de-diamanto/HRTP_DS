#!/usr/bin/env python3
"""
Converts TH01 STAGE?.DAT scene layouts into C headers for the DS port's
BG1 stage-object tile layer.

The original 20x10 grid of 32x32 world pixels is retained losslessly.
Rows begin at original y=64; horizontal scrolling is a rendering concern.

Cell data is emitted losslessly: the raw card bit and the raw obstacle
type byte (including the OT_ACTUALLY_A_*FLIP_CARD HP smuggle), so the
game code applies exactly ReC98's interpretation rules.

Output: one header per scene, `stagedat<N>.h`:

    typedef struct {
        uint8_t obstacle[10][20];  // obstacle_type_t values (0 = none)
        uint8_t card[10][20];      // 1 = plain card present
        uint8_t used;              // 0 for the unused boss-stage data
    } ds_stage_layout_t;
    extern const ds_stage_layout_t ds_stagedat<N>[5];

Usage:
    python3 stagedat_to_h.py assets/packfile/STAGE0.DAT -o assets/processed/stagedat
    python3 stagedat_to_h.py assets/packfile/STAGE*.DAT -o assets/processed/stagedat
"""

import argparse
import re
import sys
from pathlib import Path

import stagedat_decode

DS_COLS = 20
DS_ROWS = 10
SRC_ROWS = stagedat_decode.STAGEOBJS_Y
SRC_COLS = stagedat_decode.STAGEOBJS_X

# Rows are bottom-aligned: source row r -> DS row r + (DS_ROWS - SRC_ROWS).
ROW_OFFSET = DS_ROWS - SRC_ROWS  # 0


def parse_columns(spec: str) -> list[int]:
    cols: list[int] = []
    for part in spec.split(","):
        m = re.fullmatch(r"(\d+)-(\d+)", part.strip())
        if m:
            cols.extend(range(int(m.group(1)), int(m.group(2)) + 1))
        elif part.strip().isdigit():
            cols.append(int(part.strip()))
        else:
            raise ValueError(f"bad column spec: {part!r}")
    if len(cols) != DS_COLS:
        raise ValueError(
            f"column spec must select exactly {DS_COLS} columns, got {len(cols)}"
        )
    if len(set(cols)) != DS_COLS:
        raise ValueError("column spec selects the same column twice")
    if set(cols) != set(range(SRC_COLS)):
        raise ValueError("column spec must retain every original source column")
    return cols


def convert(stage: dict, columns: list[int]) -> dict:
    obstacle = [[0] * DS_COLS for _ in range(DS_ROWS)]
    card = [[0] * DS_COLS for _ in range(DS_ROWS)]

    for c in stage["cards"]:
        dst_x = columns.index(c["x"]) if c["x"] in columns else -1
        dst_y = c["y"] + ROW_OFFSET
        if dst_x < 0:
            continue
        card[dst_y][dst_x] = 1

    for o in stage["obstacles"]:
        dst_x = columns.index(o["x"]) if o["x"] in columns else -1
        dst_y = o["y"] + ROW_OFFSET
        if dst_x < 0:
            continue
        obstacle[dst_y][dst_x] = o["type"]

    return {
        "obstacle": obstacle,
        "card": card,
        "used": 0 if stage["is_boss_stage"] else 1,
    }


def write_header(path: Path, scene: int, layouts: list[dict], columns: list[int]) -> None:
    guard = f"STAGEDAT{scene}_H"
    lines = [
        f"// Generated by tools/stagedat_to_h.py from STAGE{scene}.DAT -- do not edit.",
        f"// Source columns kept: {','.join(str(c) for c in columns)}",
        f"// Source rows bottom-aligned at DS rows {ROW_OFFSET}..{DS_ROWS - 1}.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "#ifndef DS_STAGE_LAYOUT_T",
        "#define DS_STAGE_LAYOUT_T",
        "typedef struct {",
        "    uint8_t obstacle[10][20];",
        "    uint8_t card[10][20];",
        "    uint8_t used;",
        "} ds_stage_layout_t;",
        "#endif",
        "",
        f"static const ds_stage_layout_t ds_stagedat{scene}[5] = {{",
    ]
    for i, lay in enumerate(layouts):
        lines.append("    {")
        for grid_name in ("obstacle", "card"):
            lines.append(f"        // {grid_name}")
            lines.append(f"        {{")
            for row in lay[grid_name]:
                lines.append("            {" + ",".join(str(v) for v in row) + "},")
            lines.append("        },")
        lines.append(f"        {lay['used']},")
        lines.append("    },")
    lines.append("};")
    lines.append("")
    path.write_text("\n".join(lines), encoding="ascii")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dat_files", nargs="+", type=Path, help="STAGE?.DAT files")
    parser.add_argument("-o", "--outdir", type=Path, required=True)
    parser.add_argument(
        "--columns",
        default="0-19",
        help="source column order (default 0-19 = all original columns)",
    )
    args = parser.parse_args()

    try:
        columns = parse_columns(args.columns)
    except ValueError as exc:
        parser.error(str(exc))

    args.outdir.mkdir(parents=True, exist_ok=True)
    for dat in args.dat_files:
        m = re.fullmatch(r"STAGE(\d+)\.DAT", dat.name.upper())
        if not m:
            print(f"error: {dat}: expected STAGE<N>.DAT", file=sys.stderr)
            return 1
        scene = int(m.group(1))
        try:
            parsed = stagedat_decode.parse_stagedat(dat.read_bytes())
        except (OSError, ValueError) as exc:
            print(f"error: {dat}: {exc}", file=sys.stderr)
            return 1
        layouts = [convert(s, columns) for s in parsed["stages"]]
        out_path = args.outdir / f"stagedat{scene}.h"
        write_header(out_path, scene, layouts, columns)
        print(f"wrote {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
