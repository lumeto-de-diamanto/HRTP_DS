#!/usr/bin/env python3
"""
Converts a 1bpp BMP sprite sheet of 8x8 cels into a C header of halved
4x4 indexed cels for the effects canvas (e.g. ReC98's th01/sprites/
pellet.bmp: 24x8 = 3 cels).

Output: const unsigned char <name>_cels[N][16], row-major 4x4,
0 = transparent, 1 = ink.
"""

import argparse
import struct
import sys
from pathlib import Path

import halve_image

CEL = 8
HALF = CEL // 2


def load_bmp(path: Path):
    data = path.read_bytes()
    off = struct.unpack_from("<I", data, 10)[0]
    w, h = struct.unpack_from("<ii", data, 18)
    row_bytes = (w + 31) // 32 * 4

    def pixel(x, y):
        row = h - 1 - y  # bottom-up
        return (data[off + row * row_bytes + x // 8] >> (7 - x % 8)) & 1

    return [[pixel(x, y) for x in range(w)] for y in range(h)], w, h


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("bmp", type=Path)
    parser.add_argument("outdir", type=Path)
    parser.add_argument("--name", required=True)
    parser.add_argument("--halve", default="rare",
                        choices=halve_image.HALF_METHODS_LIST)
    args = parser.parse_args()

    try:
        img, w, h = load_bmp(args.bmp)
    except (OSError, ValueError, struct.error) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    if h != CEL or w % CEL:
        print(f"error: expected N x 8 sheet of 8x8 cels, got {w}x{h}",
              file=sys.stderr)
        return 1

    cels = []
    for i in range(w // CEL):
        cel = [row[i * CEL:(i + 1) * CEL] for row in img]
        cels.append(halve_image.shrink_image(cel, args.halve))

    lines = [
        f"// Generated by tools/mono_bmp_to_h.py from {args.bmp.name} -- do not edit.",
        f"// {len(cels)} cels of {HALF}x{HALF}, row-major, 0 = transparent, 1 = ink.",
        "#pragma once",
        "",
        f"static const unsigned char {args.name}_cels[{len(cels)}][{HALF * HALF}] = {{",
    ]
    for cel in cels:
        flat = [p for row in cel for p in row]
        lines.append("    {" + ", ".join(str(v) for v in flat) + "},")
    lines.append("};")
    lines.append("")

    args.outdir.mkdir(parents=True, exist_ok=True)
    out = args.outdir / f"{args.name}.h"
    out.write_text("\n".join(lines), encoding="ascii")
    print(f"wrote {out} ({len(cels)} cels)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
