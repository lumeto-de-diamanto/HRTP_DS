#!/usr/bin/env python3
"""
Extracts the 8x16 ANK glyphs from a PC-98 character-ROM sheet
(font.bmp / the Neko Project II font, identical layout) into a C
header for the DS font renderer.

Layout (empirically established, docs/th01-code-analysis.md section 7):
the sheet is 2048x2048 1bpp = 128x128 slots of 16x16. The top row holds
the 8x16 ANK set, two glyphs per slot: code c lives in slot column c//2,
left half if c is even, right half if odd. Codes 0x00-0x1F show the
PC-98 control-code mnemonics (SH, SX, ... EB), 0x20+ are the printable
glyphs. Ink pixels are 0 bits. The 16x16 JIS block below is extracted by
tools/font16x16.py.

Output: const unsigned char font8x16[96][32] for codes 0x20..0x7F, one
byte per row, MSB = leftmost pixel, 1 = ink.
"""

import argparse
import struct
import sys
from pathlib import Path

SHEET_SIZE = 2048
GLYPH_W = 8
GLYPH_H = 16
FIRST_CODE = 0x20
LAST_CODE = 0x7F


def load_sheet(path: Path) -> list[list[int]]:
    data = path.read_bytes()
    off = struct.unpack_from("<I", data, 10)[0]
    row_bytes = SHEET_SIZE // 8

    def pixel(x: int, y: int) -> int:
        # BMP rows are bottom-up; ink is a 0 bit.
        row = SHEET_SIZE - 1 - y
        return 1 - ((data[off + row * row_bytes + x // 8] >> (7 - x % 8)) & 1)

    return [[pixel(x, y) for x in range(SHEET_SIZE)] for y in range(GLYPH_H)]


def glyph_rows(sheet: list[list[int]], code: int) -> list[int]:
    col = code // 2
    half = code % 2
    x0 = col * SHEET_W_PER_SLOT + half * GLYPH_W
    rows = []
    for y in range(GLYPH_H):
        byte = 0
        for x in range(GLYPH_W):
            byte = (byte << 1) | sheet[y][x0 + x]
        rows.append(byte)
    return rows


SHEET_W_PER_SLOT = 16


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("sheet", type=Path, help="PC-98 font sheet (.bmp)")
    parser.add_argument("outdir", type=Path)
    parser.add_argument("--name", default="font8x16")
    args = parser.parse_args()

    try:
        sheet = load_sheet(args.sheet)
    except (OSError, ValueError, struct.error) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    glyphs = [glyph_rows(sheet, c) for c in range(FIRST_CODE, LAST_CODE)]

    lines = [
        f"// Generated by tools/font_atlas.py from {args.sheet.name} -- do not edit.",
        f"// 8x16 ANK glyphs for codes 0x{FIRST_CODE:02X}..0x{LAST_CODE:02X}; "
        "one byte per row, MSB = leftmost pixel, 1 = ink.",
        "#pragma once",
        "",
        f"static const unsigned char {args.name}[96][32] = {{",
    ]
    for i, rows in enumerate(glyphs):
        code = FIRST_CODE + i
        ch = chr(code) if code >= 0x21 else " "
        comment = f" // '{ch}'" if ch.isprintable() and ch != "/" else ""
        body = ", ".join(f"0x{b:02X}" for b in rows)
        lines.append(f"    {{{body}}},{comment}")
    lines.append("};")
    lines.append("")

    args.outdir.mkdir(parents=True, exist_ok=True)
    out = args.outdir / f"{args.name}.h"
    out.write_text("\n".join(lines), encoding="ascii")
    print(f"wrote {out} ({len(glyphs)} glyphs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
